export const USAGE_TEMPLATES: UsageTemplate[] = TEMPLATES.map(({ id, label, description, fields }) => ({ id, label, description, fields }));

export function renderTemplate(id: string, values: Record<string, any>, ctx: TemplateRenderCtx): RenderResult {
  const tpl = TEMPLATES.find(t => t.id === id);
  if (!tpl) return { ok: false, error: `unknown template '${id}'` };
  const name = values?.name;
  if (id !== 'clone-builtin' && (!name || !/^[a-z0-9][a-z0-9-]{0,63}$/.test(String(name)))) {
    return { ok: false, error: '插件名必填且只能含小写字母/数字/连字符' };
  }
  const missing = tpl.fields.filter(f => f.required && (values?.[f.key] === undefined || values?.[f.key] === ''));
  if (id !== 'clone-builtin' && missing.length > 0) {
    return { ok: false, error: `缺少必填字段: ${missing.map(f => f.label).join(', ')}` };
  }
  return tpl.render(values ?? {}, ctx);
}
