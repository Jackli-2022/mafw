/**
 * `mafw plugin init` templates — inline strings, never files copied at build
 * time.
 *
 * The scaffold is not a demo: it is the smallest package that already passes
 * `mafw plugin check` (and therefore `PluginHost.checkPackage`). Its
 * `plugin.json` declares exactly the planes its `index.js` registers, so an
 * author starts *inside* the standard's bounds instead of discovering them by
 * failing the check. Anything added later must be declared first; anything
 * declared but never registered stays legal.
 */

export interface PluginTemplateFiles {
  'plugin.json': string;
  'index.js': string;
  'README.md': string;
}

/**
 * The manifest's package-name rule, kept literally in sync with `NAME_PATTERN`
 * in `../plugins/package-manifest.ts` plus its trailing dot/space rejection.
 *
 * That parser stays the source of truth; the copy exists so `init` refuses a
 * name *before* it creates a directory that could never activate. The tests pin
 * the two together (every name here must agree with `parsePackageManifest`).
 */
const NAME_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

/**
 * `init`'s only rule on top of the manifest's: a length ceiling.
 *
 * The scaffold registers `plugin:<name>:ping`; at 100 characters that type is
 * 112 — still inside the 128-character ceiling the plugin standard uses for
 * name-like identifiers, with room to grow. It also keeps the scaffolded
 * directory name sane.
 *
 * Deliberately **not** a parser rule: a hand-written package may legitimately
 * use a longer name, and pushing the cap into `parsePackageManifest` would force
 * it into the published JSON Schema too, where it would contradict the manifest
 * rule (and `init` would no longer be a subset of it).
 */
export const PACKAGE_NAME_MAX_LENGTH = 100;

/** Printed right after `invalid package name: <name>`. */
export const PACKAGE_NAME_RULE =
  'name must start with a letter or digit, contain only letters, digits, ".", "_" or "-", '
  + 'and must not end with "." or " "';

export function isValidPackageName(name: string): boolean {
  return name.length <= PACKAGE_NAME_MAX_LENGTH
    && NAME_PATTERN.test(name)
    && !/[. ]$/.test(name);
}

/**
 * Why `init` refuses this name (the exact message), or `null` when it accepts
 * it. The length rule is named separately so the caller can say *which* rule
 * failed instead of a generic "invalid package name".
 */
export function packageNameError(name: string): string | null {
  if (name.length > PACKAGE_NAME_MAX_LENGTH) {
    return `package name must be at most ${PACKAGE_NAME_MAX_LENGTH} characters`;
  }
  if (!isValidPackageName(name)) return `invalid package name: ${name}`;
  return null;
}

function manifestTemplate(name: string, eventType: string): string {
  // `contributes.gateway` is the static upper bound (declared ⊇ registered):
  // list every plane `activate()` registers, and opt out of the http plane the
  // scaffold does not use, so a later `ctx.http.route(...)` fails loudly.
  const manifest = {
    name,
    version: '0.1.0',
    main: 'index.js',
    apiVersion: 2,
    kind: 'trusted',
    permissions: ['actions', 'events'],
    contributes: {
      gateway: {
        actions: ['ping'],
        events: [eventType],
        // Explicit zero bounds instead of "absent = unbounded": the scaffold
        // teaches that a plane must be declared before anything may register in
        // it, so adding a tool later means editing this block first.
        tools: [],
        observers: [],
        http: false,
      },
    },
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function indexTemplate(name: string, eventType: string): string {
  // No backticks in this source: it is pasted into a user's editor as-is.
  // Deliberately timer-free — a background loop would have to be released via
  // ctx.effect(...) to survive a reload, which is the wrong first lesson.
  return `/**
 * ${name} - generated by "mafw plugin init"; replace this body with real work.
 *
 * Only what activate() returns is registered, and everything registered must
 * first be declared in plugin.json "contributes.gateway" (the declaration is an
 * upper bound). There is no background work here on purpose: a timer or socket
 * has to be released through ctx.effect(...) or it outlives a reload.
 */
module.exports = {
  name: '${name}',
  async activate(ctx) {
    // ctx.emit is package-scoped: it can only publish events this package
    // declared, and only once something actually happens. Never on a timer.
    //   ctx.emit({ type: '${eventType}', properties: { at: Date.now() } });

    return {
      actions: {
        ping: {
          title: 'Ping',
          description: 'Scaffold action; answers { pong: true }.',
          handler: () => ({ pong: true }),
        },
      },
      events: [
        {
          type: '${eventType}',
          title: 'Ping',
          schema: { type: 'object', properties: { at: { type: 'number' } } },
        },
      ],
    };
  },
};
`;
}

function readmeTemplate(name: string, eventType: string): string {
  return `# ${name}

Generated by \`mafw plugin init\`: one action (\`ping\`) and one event
(\`${eventType}\`). Replace them instead of adding undeclared ones —
\`plugin.json\` \`contributes.gateway\` is an upper bound, so anything registered
but not declared fails the check.

\`contributes.gateway\` ships with \`tools: []\` and \`observers: []\`: those
planes are open at zero, so adding a tool or an observer later means editing
\`contributes.gateway\` first. Declaring the plane empty is the point — an
absent plane means "unbounded", which is not what a fresh package should say.

Check it (gateway does not need to be running; pass an absolute path):

    mafw plugin check "<absolute path to this folder>"

A human runs this — an \`apiVersion: 2\` package needs explicit trust and
permission consent, and the command reads the human credential:

    mafw plugins install "<absolute path to this folder>" --trust trusted --permission actions --permission events

Keep those \`--permission\` flags in sync with \`plugin.json\` \`permissions\`.
`;
}

/**
 * The three files of a scaffolded package.
 *
 * The name is validated here even though the caller already did: every template
 * embeds it inside generated source, and a call with a name the manifest would
 * reject must fail before it can produce a package that never activates.
 */
export function pluginTemplates(name: string): PluginTemplateFiles {
  const error = packageNameError(name);
  if (error !== null) throw new Error(error);
  const eventType = `plugin:${name}:ping`;
  return {
    'plugin.json': manifestTemplate(name, eventType),
    'index.js': indexTemplate(name, eventType),
    'README.md': readmeTemplate(name, eventType),
  };
}
