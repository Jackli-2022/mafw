/**
 * M0: loopback tunnel terminator.
 *
 * cloudflared (and later the relay host client) must never point at `:3000`
 * directly. This proxy listens on loopback, strips any client-supplied
 * `x-mafw-tunnel`, injects the process secret, and forwards HTTP + WebSocket
 * upgrades to the gateway. The gateway then resolves a `relay` principal
 * instead of trusting the loopback socket.
 */
import * as crypto from 'crypto';
import * as http from 'http';
import * as net from 'net';
import { TUNNEL_HEADER } from '../core/auth';

export interface TunnelTerminatorOptions {
  /** Per-process secret; generated by `newTunnelSecret()`. */
  secret: string;
  /** Gateway HTTP port (usually 3000). */
  targetPort: number;
  targetHost?: string;
  listenHost?: string;
  /** Default 3001; 0 picks an ephemeral port (tests). */
  listenPort?: number;
}

export interface TunnelTerminator {
  start(): Promise<number>;
  stop(): Promise<void>;
  port(): number | null;
}

export function newTunnelSecret(): string {
  return crypto.randomBytes(32).toString('hex');
}

export function createTunnelTerminator(opts: TunnelTerminatorOptions): TunnelTerminator {
  const targetHost = opts.targetHost ?? '127.0.0.1';
  const listenHost = opts.listenHost ?? '127.0.0.1';
  const listenPort = opts.listenPort ?? 3001;

  let server: http.Server | null = null;
  let boundPort: number | null = null;
  const sockets = new Set<net.Socket>();
  const upstreamSockets = new Set<net.Socket>();

  function headersWithSecret(req: http.IncomingMessage): http.OutgoingHttpHeaders {
    const headers: http.OutgoingHttpHeaders = { ...req.headers };
    delete headers[TUNNEL_HEADER];
    headers[TUNNEL_HEADER] = opts.secret;
    return headers;
  }

  function proxyRequest(req: http.IncomingMessage, res: http.ServerResponse): void {
    const upstream = http.request(
      {
        host: targetHost,
        port: opts.targetPort,
        path: req.url,
        method: req.method,
        headers: headersWithSecret(req),
        agent: false,
      },
      (upstreamRes) => {
        res.writeHead(upstreamRes.statusCode ?? 502, upstreamRes.headers);
        upstreamRes.pipe(res);
      },
    );
    upstream.on('socket', (socket) => {
      upstreamSockets.add(socket);
      socket.on('close', () => upstreamSockets.delete(socket));
    });
    upstream.on('error', () => {
      if (!res.headersSent) {
        res.writeHead(502, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ error: 'tunnel target unavailable' }));
        return;
      }
      res.destroy();
    });
    req.pipe(upstream);
  }

  function proxyUpgrade(req: http.IncomingMessage, socket: net.Socket, head: Buffer): void {
    const upstreamReq = http.request({
      host: targetHost,
      port: opts.targetPort,
      path: req.url,
      method: req.method,
      headers: headersWithSecret(req),
      agent: false,
    });

    upstreamReq.on('upgrade', (upstreamRes, upstreamSocket, upstreamHead) => {
      upstreamSockets.add(upstreamSocket as net.Socket);
      upstreamSocket.on('close', () => upstreamSockets.delete(upstreamSocket as net.Socket));
      const lines = [`HTTP/1.1 ${upstreamRes.statusCode ?? 101} ${upstreamRes.statusMessage || 'Switching Protocols'}`];
      for (let i = 0; i < upstreamRes.rawHeaders.length; i += 2) {
        lines.push(`${upstreamRes.rawHeaders[i]}: ${upstreamRes.rawHeaders[i + 1]}`);
      }
      socket.write(`${lines.join('\r\n')}\r\n\r\n`);
      if (upstreamHead.length > 0) socket.write(upstreamHead);
      if (head.length > 0) upstreamSocket.write(head);
      upstreamSocket.on('error', () => socket.destroy());
      socket.on('error', () => upstreamSocket.destroy());
      upstreamSocket.pipe(socket);
      socket.pipe(upstreamSocket);
    });

    upstreamReq.on('response', (upstreamRes) => {
      socket.write(
        `HTTP/1.1 ${upstreamRes.statusCode ?? 502} ${upstreamRes.statusMessage || 'Bad Gateway'}\r\n`
        + 'Connection: close\r\n\r\n',
      );
      socket.destroy();
    });

    upstreamReq.on('error', () => {
      try {
        socket.write('HTTP/1.1 502 Bad Gateway\r\nConnection: close\r\n\r\n');
      } catch { /* socket already gone */ }
      socket.destroy();
    });

    upstreamReq.end();
  }

  return {
    async start(): Promise<number> {
      if (server && boundPort !== null) return boundPort;

      await new Promise<void>((resolve, reject) => {
        const next = http.createServer((req, res) => proxyRequest(req, res));
        next.on('upgrade', (req, socket, head) => proxyUpgrade(req, socket as net.Socket, head));
        next.on('connection', (socket) => {
          sockets.add(socket);
          socket.on('close', () => sockets.delete(socket));
        });
        next.once('error', (err) => {
          try { next.close(); } catch { /* already closed */ }
          reject(err);
        });
        next.listen(listenPort, listenHost, () => {
          next.removeAllListeners('error');
          next.on('error', () => { /* keep serving; errors are per-request */ });
          server = next;
          boundPort = (next.address() as net.AddressInfo).port;
          resolve();
        });
      });

      return boundPort as number;
    },

    async stop(): Promise<void> {
      const current = server;
      server = null;
      boundPort = null;
      for (const socket of sockets) socket.destroy();
      sockets.clear();
      for (const socket of upstreamSockets) socket.destroy();
      upstreamSockets.clear();
      if (!current) return;
      await new Promise<void>((resolve) => current.close(() => resolve()));
    },

    port(): number | null {
      return boundPort;
    },
  };
}
