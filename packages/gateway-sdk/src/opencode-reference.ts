/**
 * opencode OpenAPI → 事件参考产物（纯函数，生成脚本与单测共用）。
 *
 * 输入：opencode 的 `packages/protocol/openapi.json`（`V2Event` 联合 +
 *       `V2EventEncoded.contentSchema`）。
 * 输出：events.gen.ts / events.json / event-map.md 的文本。
 *
 * 为什么单独做：`@mafw/sdk` 不携带 runtime 原生类型（View DTO 边界）。
 * 这些产物是给 runtime 插件作者的「上游参考」，放在 docs/reference，不进 SDK 构建。
 */

export interface OpenApiSpecLike {
  openapi?: string
  info?: { title?: string; version?: string }
  components?: { schemas?: Record<string, any> }
}

export interface EventVariant {
  /** components.schemas 的名字（通常与 type 相同） */
  schema: string
  /** `properties.type` 的字符串字面量；模板/pattern 变体为 null */
  type: string | null
  /** true = `rpc.${string}` 这类前缀事件 */
  rpc?: boolean
  required: string[]
  properties: string[]
}

export interface EventReference {
  schema: string
  variants: EventVariant[]
}

export interface RenderMeta {
  /** spec 来源（路径或 URL） */
  source: string
  /** 字节数（用于 README/注释） */
  bytes: number
  /** sha256（可选） */
  sha256?: string
}

const SCHEMA_PREFIX = '#/components/schemas/'

function refName(ref: unknown): string | null {
  return typeof ref === 'string' && ref.startsWith(SCHEMA_PREFIX)
    ? ref.slice(SCHEMA_PREFIX.length)
    : null
}

/**
 * 从 OpenAPI 文档提取事件联合。
 * 缺 schema 时抛出明确错误：运行中 serve 的旧 spec 没有 `V2Event`。
 */
export function extractEventReference(spec: OpenApiSpecLike, schemaName = 'V2Event'): EventReference {
  const schemas = spec.components?.schemas ?? {}
  const union = schemas[schemaName]
  if (!union) {
    throw new Error(
      `components.schemas.${schemaName} is missing — the spec has no event union. ` +
      `A running instance's /openapi.json can be an older build; use opencode's ` +
      `packages/protocol/openapi.json (or run 'bun run generate' in packages/protocol).`,
    )
  }
  const entries: any[] = union.anyOf ?? union.oneOf ?? []
  if (entries.length === 0) {
    throw new Error(`components.schemas.${schemaName} has no anyOf/oneOf variants`)
  }

  const variants: EventVariant[] = []
  for (const entry of entries) {
    const name = refName(entry?.$ref)
    if (!name) {
      // inline union 变体：没有稳定 schema 名，按 type 字面量命名（避免静默丢事件）
      const t = entry?.properties?.type
      const type = typeof t?.const === 'string' ? t.const : Array.isArray(t?.enum) ? t.enum[0] : null
      variants.push({
        schema: type ?? '(inline)',
        type: typeof type === 'string' ? type : null,
        ...(type === null ? { rpc: true } : {}),
        required: Array.isArray(entry?.required) ? entry.required : [],
        properties: Object.keys(entry?.properties ?? {}),
      })
      continue
    }
    const schema = schemas[name] ?? {}
    const t = schema.properties?.type
    const literal = typeof t?.const === 'string'
      ? t.const
      : Array.isArray(t?.enum) && typeof t.enum[0] === 'string' ? t.enum[0] : null
    variants.push({
      schema: name,
      type: literal,
      ...(literal === null && typeof t?.pattern === 'string' ? { rpc: true } : {}),
      required: Array.isArray(schema.required) ? schema.required : [],
      properties: Object.keys(schema.properties ?? {}),
    })
  }

  return { schema: schemaName, variants }
}

function header(meta: RenderMeta, ref: EventReference): string {
  return [
    '/**',
    ' * AUTO-GENERATED by packages/gateway-sdk/scripts/gen-opencode-reference.ts',
    ` * source: ${meta.source} (${meta.bytes} bytes${meta.sha256 ? `, sha256 ${meta.sha256}` : ''})`,
    ` * schema: ${ref.schema} (${ref.variants.length} variants)`,
    ' * do not edit by hand.',
    ' */',
  ].join('\n')
}

export function renderEventsTs(ref: EventReference, meta: RenderMeta): string {
  const types = ref.variants
    .map((v) => v.type)
    .filter((t): t is string => typeof t === 'string')
    .sort((a, b) => a.localeCompare(b))
  const rpc = ref.variants.filter((v) => v.rpc).map((v) => v.schema)

  return [
    header(meta, ref),
    "import type { components } from './types.gen'",
    '',
    '/** opencode SSE 事件联合（wire 的 `data` 是 JSON 字符串，解码后为此类型）。 */',
    `export type OpencodeEvent = components['schemas']['${ref.schema}']`,
    '',
    '/** 事件 type 字面量（排序；用于过滤 / 穷尽检查）。 */',
    'export const OPENCODE_EVENT_TYPES = [',
    ...types.map((t) => `  '${t}',`),
    '] as const',
    '',
    'export type OpencodeEventType = (typeof OPENCODE_EVENT_TYPES)[number]',
    '',
    ...(rpc.length > 0
      ? [
          `/** 模板事件（无固定 type）：${rpc.join(', ')} */`,
          "export const OPENCODE_RPC_PREFIX = 'rpc.' as const",
          '',
        ]
      : []),
  ].join('\n')
}

export function renderEventsJson(ref: EventReference, meta: RenderMeta): string {
  const out = {
    $comment: 'Auto-generated by packages/gateway-sdk/scripts/gen-opencode-reference.ts — do not edit by hand.',
    source: meta.source,
    bytes: meta.bytes,
    ...(meta.sha256 ? { sha256: meta.sha256 } : {}),
    schema: ref.schema,
    count: ref.variants.length,
    events: [...ref.variants]
      .sort((a, b) => (a.type ?? a.schema).localeCompare(b.type ?? b.schema))
      .map((v) => ({
        type: v.type,
        schema: v.schema,
        ...(v.rpc ? { rpc: true } : {}),
        required: v.required,
        properties: v.properties,
      })),
  }
  return JSON.stringify(out, null, 2) + '\n'
}

/** 名称启发式（仅在 canonical 里存在时返回；全部需要人工确认）。 */
const RULES: Array<[RegExp, string]> = [
  [/^session\.execution\.started$/, 'turn.started'],
  [/^session\.execution\.(succeeded|completed)$/, 'turn.completed'],
  [/^session\.execution\.failed$/, 'turn.failed'],
  [/^session\.execution\.interrupted$/, 'turn.aborted'],
  [/^session\.idle$/, 'turn.completed'],
  [/^session\.error$/, 'turn.failed'],
  [/^(message\.part\.(updated|created)|part\.updated)$/, 'part.updated'],
  [/^(message\.part\.delta|part\.delta)$/, 'part.delta'],
  [/^todo\.updated$/, 'plan.updated'],
]

export function suggestCanonical(type: string | null, canonical: readonly string[]): string | null {
  if (!type) return null
  const set = new Set(canonical)
  if (set.has(type)) return type
  for (const [re, target] of RULES) {
    if (re.test(type) && set.has(target)) return target
  }
  return null
}

export function renderEventMapMd(
  ref: EventReference,
  canonical: readonly string[],
  meta: RenderMeta,
): string {
  const rows = [...ref.variants]
    .sort((a, b) => (a.type ?? a.schema).localeCompare(b.type ?? b.schema))
    .map((v) => {
      const suggested = suggestCanonical(v.type, canonical)
      const label = v.type ? `\`${v.type}\`` : `\`${v.schema}\`（rpc 前缀）`
      return `| ${label} | \`${v.schema}\` | ${suggested ? `\`${suggested}\`` : '—'} |`
    })

  return [
    '# opencode 事件 → MAFW canonical（建议表）',
    '',
    '> AUTO-GENERATED by `packages/gateway-sdk/scripts/gen-opencode-reference.ts`.',
    `> source: ${meta.source} (${meta.bytes} bytes${meta.sha256 ? `, sha256 ${meta.sha256}` : ''})`,
    '> `建议` 列只是名称启发式，**必须人工确认**；`—` = 没有直接对应，需要在插件里组合或显式 drop。',
    `> MAFW canonical 清单：\`packages/gateway-sdk/src/events.ts\`（${canonical.length} 个）。`,
    '',
    '| opencode type | schema | 建议 MAFW canonical |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n')
}

export function renderReadme(
  ref: EventReference,
  canonical: readonly string[],
  meta: RenderMeta,
): string {
  const mapped = ref.variants.filter((v) => suggestCanonical(v.type, canonical)).length
  return [
    '# opencode API 参考（生成物）',
    '',
    '> AUTO-GENERATED by `packages/gateway-sdk/scripts/gen-opencode-reference.ts`.',
    `> source: \`${meta.source}\`（${meta.bytes} bytes${meta.sha256 ? `，sha256 \`${meta.sha256}\`` : ''}）`,
    '',
    '这个目录是给 **runtime 插件作者** 的上游参考，不属于 `@mafw/sdk` 的运行时契约',
    '（MAFW 客户端只消费中立的 View DTO，不携带 opencode 原生类型）。',
    '',
    '| 文件 | 用途 |',
    '|---|---|',
    '| `types.gen.ts` | openapi-typescript 全量类型：`paths` / `operations` / `components.schemas` |',
    '| `events.gen.ts` | `OpencodeEvent` 联合（`V2Event`）+ `OPENCODE_EVENT_TYPES` 清单 |',
    '| `events.json` | 机器可读事件清单（type / schema / required / properties） |',
    '| `event-map.md` | opencode → MAFW canonical 建议表（需人工确认） |',
    '',
    `事件：**${ref.variants.length}** 个变体，其中名称启发式可对上 MAFW canonical 的 **${mapped}** 个。`,
    '',
    '## 重新生成',
    '',
    '```bash',
    '# 优先用 opencode 仓库的 protocol spec（运行中 serve 的 /openapi.json 可能是旧构建）',
    'npm run gen:opencode-ref -- --spec https://raw.githubusercontent.com/anomalyco/opencode/dev/packages/protocol/openapi.json',
    '',
    '# 或本地文件',
    'npm run gen:opencode-ref -- --spec ../../.tmp/opencode-openapi.json',
    '```',
    '',
    '`--check` 只比对不写（CI 用）。',
    '',
  ].join('\n')
}
